// Command report renders docs/results.md, docs/benchmarks.md and the README
// results block from test-results/*.json. Every number comes from those
// artifacts; nothing is typed by hand.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/effecttrace/effecttrace/test/experiments"
)

const (
	readmeStart = "<!-- results:start (generated by make test-results; do not edit) -->"
	readmeEnd   = "<!-- results:end -->"
)

type benchFile struct {
	Kind        string            `json:"kind"`
	Description string            `json:"description"`
	GeneratedAt string            `json:"generatedAt"`
	Commit      string            `json:"commit"`
	Host        map[string]string `json:"host"`
	Benchmarks  []struct {
		Name          string  `json:"name"`
		Actions       int     `json:"concurrentActions"`
		Records       int     `json:"records"`
		MsPerOp       float64 `json:"msPerOp"`
		BytesPerOp    int64   `json:"bytesPerOp"`
		AllocsPerOp   int64   `json:"allocsPerOp"`
		RecordsPerSec float64 `json:"recordsPerSecond"`
	} `json:"benchmarks"`
	MemoryPerAct map[string]int64 `json:"retainedHeapBytesPerAction"`
}

type envFile struct {
	Commit     string            `json:"commit"`
	Components map[string]string `json:"components"`
	Host       map[string]string `json:"host"`
}

func main() {
	dir := flag.String("dir", "test-results", "results directory")
	docs := flag.String("docs", "docs", "docs directory")
	readme := flag.String("readme", "README.md", "README to update between result markers")
	flag.Parse()
	var rf experiments.ResultsFile
	must(readJSON(filepath.Join(*dir, "results.json"), &rf))
	var sum experiments.Summary
	must(readJSON(filepath.Join(*dir, "summary.json"), &sum))
	var env envFile
	_ = readJSON(filepath.Join(*dir, "environment.json"), &env)
	var bf benchFile
	hasBench := readJSON(filepath.Join(*dir, "benchmarks.json"), &bf) == nil

	must(os.WriteFile(filepath.Join(*docs, "results.md"), []byte(resultsMD(&rf, &sum, &env)), 0o644)) // #nosec G306 -- public docs
	if hasBench {
		must(os.WriteFile(filepath.Join(*docs, "benchmarks.md"), []byte(benchMD(&bf)), 0o644)) // #nosec G306 -- public docs
	}
	if b, err := os.ReadFile(*readme); err == nil {
		s := string(b)
		i, j := strings.Index(s, readmeStart), strings.Index(s, readmeEnd)
		if i >= 0 && j > i {
			s = s[:i+len(readmeStart)] + "\n" + readmeBlock(&sum, &env, hasBench, &bf) + "\n" + s[j:]
			must(os.WriteFile(*readme, []byte(s), 0o644)) // #nosec G306 -- public docs
		}
	}
	fmt.Println("rendered docs/results.md, docs/benchmarks.md and README results block")
}

func readJSON(path string, v any) error {
	b, err := os.ReadFile(path) // #nosec G304 -- fixed artifact paths
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func pct(p *float64) string {
	if p == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.3f", *p)
}

func short(sha string) string {
	if len(sha) > 12 {
		return sha[:12]
	}
	return sha
}

func icon(status string) string {
	switch status {
	case "pass":
		return "✅ pass"
	case "fail":
		return "❌ fail"
	case "error":
		return "⚠️ error"
	default:
		return "➖ " + status
	}
}

func readmeBlock(s *experiments.Summary, env *envFile, hasBench bool, bf *benchFile) string {
	var b strings.Builder
	a := s.Attribution
	fmt.Fprintf(&b, "| Experiments | Pass | Fail | Error | Unsupported |\n|---:|---:|---:|---:|---:|\n| %d | %d | %d | %d | %d |\n\n",
		s.Scenarios["total"], s.Scenarios["pass"], s.Scenarios["fail"], s.Scenarios["error"], s.Scenarios["unsupported"])
	fmt.Fprintf(&b, "| Live kind attribution (%d actions) | Value |\n|---|---:|\n", a.Actions)
	fmt.Fprintf(&b, "| Direct precision / recall | %s / %s |\n", pct(a.Direct.Precision), pct(a.Direct.Recall))
	fmt.Fprintf(&b, "| Structural precision / recall | %s / %s |\n", pct(a.Structural.Precision), pct(a.Structural.Recall))
	fmt.Fprintf(&b, "| False attachments | %d |\n| Unrelated telemetry attachments | %d |\n| Claims on ambiguous changes | %d |\n", a.FalseAttachments, a.UnrelatedTelemetry, a.AmbiguousClaims)
	fmt.Fprintf(&b, "| Concurrent-action separation | %d / %d |\n\n", a.ConcurrentSeparated, a.ConcurrentScenarios)
	dirty := ""
	if s.Dirty {
		dirty = " (uncommitted changes present)"
	}
	fmt.Fprintf(&b, "<sub>Generated from [`test-results/`](test-results/) at commit `%s`%s on Kubernetes %s in a single-node kind cluster on a laptop. Not a production-scale measurement. Details: [docs/results.md](docs/results.md)", short(s.Commit), dirty, env.Components["kubernetes"])
	if hasBench {
		b.WriteString(" · synthetic engine benchmarks: [docs/benchmarks.md](docs/benchmarks.md)")
	}
	b.WriteString(".</sub>")
	return b.String()
}

func resultsMD(rf *experiments.ResultsFile, s *experiments.Summary, env *envFile) string {
	var b strings.Builder
	b.WriteString("# Experiment results\n\n> Generated by `make test-results` from `test-results/*.json`. Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "Commit `%s`", short(s.Commit))
	if s.Dirty {
		b.WriteString(" (working tree had uncommitted changes)")
	}
	fmt.Fprintf(&b, " · generated %s\n\n", s.GeneratedAt.UTC().Format("2006-01-02 15:04 MST"))
	b.WriteString("## Summary\n\n")
	b.WriteString(readmeBlock(s, env, false, nil))
	b.WriteString("\n\nPrecision and recall are micro-averaged over every action of the live kind experiments; ")
	b.WriteString(s.Attribution.Scope + ". A claim is an object in a graph whose path from the action is ATTRIBUTED; objects reachable only through TEMPORAL_CORRELATION are not counted as claims. The ground-truth method is described in [testing.md](testing.md).\n\n")
	b.WriteString("## Operational measurements (live lab)\n\n| Measurement | n | p50 | p95 | max |\n|---|---:|---:|---:|---:|\n")
	row := func(name, unit string, st *experiments.Stat) {
		if st == nil {
			fmt.Fprintf(&b, "| %s | 0 | – | – | – |\n", name)
			return
		}
		fmt.Fprintf(&b, "| %s | %d | %.3g %s | %.3g %s | %.3g %s |\n", name, st.N, st.P50, unit, st.P95, unit, st.Max, unit)
	}
	row("Action issued → first STRUCTURAL edge visible", "s", s.Operational.FirstEffectSeconds)
	row("Action issued → graph COMPLETE (incl. settle and telemetry windows)", "s", s.Operational.CompleteSeconds)
	row("Graph query (GET /api/v1/effects/{id})", "ms", s.Operational.QueryMilliseconds)
	b.WriteString("\n" + s.Operational.Note + "\n\n")
	b.WriteString("## Scenarios\n\n| ID | Category | Scenario | Result | Checks |\n|---|---|---|---|---:|\n")
	for _, r := range rf.Scenarios {
		passed := 0
		for _, c := range r.Checks {
			if c.Pass {
				passed++
			}
		}
		fmt.Fprintf(&b, "| [%s](#%s) | %s | %s | %s | %d/%d |\n", r.ID, strings.ToLower(r.ID), r.Category, r.Title, icon(r.Status), passed, len(r.Checks))
	}
	b.WriteString("\n## Details\n")
	for _, r := range rf.Scenarios {
		fmt.Fprintf(&b, "\n### %s\n\n**%s** · %s · %s", r.ID, r.Title, r.Category, icon(r.Status))
		if r.DurationS > 0 {
			fmt.Fprintf(&b, " · %.0f s", r.DurationS)
		}
		fmt.Fprintf(&b, "\n\n%s\n", r.Description)
		if r.Error != "" {
			fmt.Fprintf(&b, "\nError: `%s`\n", strings.ReplaceAll(r.Error, "`", "'"))
		}
		if len(r.Actions) > 0 {
			b.WriteString("\n| Action | Direct tp/fp/fn | Structural tp/fp/fn | False attachments | Ambiguities | Exclusions |\n|---|---|---|---:|---:|---:|\n")
			for _, o := range r.Actions {
				ev := o.Eval
				fmt.Fprintf(&b, "| %s | %d/%d/%d | %d/%d/%d | %d | %d | %d |\n", o.Label, ev.Direct.TP, ev.Direct.FP, ev.Direct.FN,
					ev.Structural.TP, ev.Structural.FP, ev.Structural.FN, len(ev.FalseAttachments), ev.Ambiguities, ev.Exclusions)
			}
		}
		if len(r.Checks) > 0 {
			b.WriteString("\n")
			for _, c := range r.Checks {
				mark := "✅"
				if !c.Pass {
					mark = "❌"
				}
				d := ""
				if c.Detail != "" {
					d = " — " + strings.ReplaceAll(c.Detail, "|", "/")
				}
				fmt.Fprintf(&b, "- %s %s%s\n", mark, c.Name, d)
			}
		}
		for _, n := range r.Notes {
			fmt.Fprintf(&b, "\n> %s\n", n)
		}
	}
	if len(env.Components) > 0 {
		b.WriteString("\n## Environment\n\n| Component | Version |\n|---|---|\n")
		for _, k := range []string{"kubernetes", "kindNodeImage", "kind", "opentelemetryCollector", "prometheus", "opentelemetryGo", "clientGo", "mcpGoSDK", "mcpProtocol", "go", "containerEngine"} {
			if v, ok := env.Components[k]; ok {
				fmt.Fprintf(&b, "| %s | %s |\n", k, v)
			}
		}
		fmt.Fprintf(&b, "| host | %s/%s, %s CPUs |\n", env.Host["os"], env.Host["arch"], env.Host["cpus"])
	}
	return b.String()
}

func benchMD(bf *benchFile) string {
	var b strings.Builder
	b.WriteString("# Benchmarks\n\n> Generated by `make benchmark` and `make test-results` from `test-results/benchmarks.json`. Do not edit by hand.\n\n")
	fmt.Fprintf(&b, "**Kind:** `%s`. %s\n\n", bf.Kind, bf.Description)
	fmt.Fprintf(&b, "Commit `%s` · %s/%s · %s CPUs · %s\n\n", short(bf.Commit), bf.Host["os"], bf.Host["arch"], bf.Host["cpus"], bf.Host["go"])
	b.WriteString("These numbers describe the correlation engine on one machine. They are separate from the live kind measurements in [results.md](results.md) and say nothing about production scale.\n\n")
	b.WriteString("| Benchmark | Concurrent actions | Records | ms/op | Allocations/op | Bytes/op | Records/s |\n|---|---:|---:|---:|---:|---:|---:|\n")
	for _, e := range bf.Benchmarks {
		rps := "–"
		if e.RecordsPerSec > 0 {
			rps = fmt.Sprintf("%.0f", e.RecordsPerSec)
		}
		fmt.Fprintf(&b, "| %s | %d | %d | %.3f | %d | %d | %s |\n", e.Name, e.Actions, e.Records, e.MsPerOp, e.AllocsPerOp, e.BytesPerOp, rps)
	}
	b.WriteString("\n| Concurrent actions | Retained heap per action (bytes) |\n|---:|---:|\n")
	for _, n := range []string{"1", "10", "50", "100"} {
		if v, ok := bf.MemoryPerAct[n]; ok {
			fmt.Fprintf(&b, "| %s | %d |\n", n, v)
		}
	}
	b.WriteString("\n- `ingest`: applying every observation record to a fresh store.\n- `index_and_graph`: discovering all actions and building one graph on a cold engine (the cost of the first query after new data).\n- `graph_query`: building one graph with a warm action index (repeated API queries).\n")
	return b.String()
}
